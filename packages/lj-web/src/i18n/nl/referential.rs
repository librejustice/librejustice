const SEAT: SeatWords = SeatWords {
    container: |container| match container {
        SeatContainer::Pole(n) => format!("afdeling {n}"),
        SeatContainer::Section(n) => format!("{n}e sectie"),
        SeatContainer::Tribunal => "Gerecht".to_string(),
        SeatContainer::TribunalFonctionPublique => "Gerecht voor ambtenarenzaken".to_string(),
    },
    chamber: |chamber, matters| match (chamber, matters) {
        (SeatChamber::Number(n), None) => format!("{n}e kamer"),
        (SeatChamber::Number(n), Some(matters)) => format!("{n}e kamer voor {matters}"),
        (SeatChamber::Letter(l), None) => format!("kamer {l}"),
        (SeatChamber::Letter(l), Some(matters)) => format!("kamer {l} voor {matters}"),
        (SeatChamber::Composed(a, b), _) => format!("kamer {a}-{b}"),
    },
    room: |matters| format!("kamer voor {matters}"),
    matter,
    and: " en ",
    section: |n| format!("{n}e sectie"),
    letter: |l| format!("sectie {l}"),
    joined: |joined| match joined {
        SeatJoined::SubSections(nums) if nums.len() == 1 => {
            format!("{}e onderafdeling", seat::numbers(nums))
        }
        SeatJoined::SubSections(nums) => {
            format!("verenigde onderafdelingen {}", seat::numbers(nums))
        }
        SeatJoined::Chambers(nums) => format!("verenigde kamers {}", seat::numbers(nums)),
    },
    formation,
    office,
    mid: seat::lower_first,
};

