fn article_status(status: &str) -> Option<&'static str> {
    Some(match status {
        "VIGUEUR" => "Geldend",
        "MODIFIE" => "Gewijzigd",
        "ABROGE" => "Opgeheven",
        "PERIME" => "Vervallen",
        "REMPLACE" => "Vervangen",
        "TRANSFERE" => "Overgebracht",
        "DEPLACE" => "Verplaatst",
        "ANNULE" => "Vernietigd",
        "DENONCE" => "Opgezegd",
        "DISJOINT" => "Afgesplitst",
        "VIGUEUR_DIFF" => "Uitgestelde inwerkingtreding",
        "ABROGE_DIFF" => "Uitgestelde opheffing",
        "MODIFIE_MORT_NE" => "Gewijzigd, nooit in werking getreden",
        _ => return None,
    })
}

