/// The decision page, and the decision vocabulary other pages show.
pub struct DecisionUi {
    pub official_translation: &'static str,
    pub translation: &'static str,
    pub automatic_translation: &'static str,
    /// What follows the status of a translation, from the name of the authentic text's language.
    pub authentic_in: fn(&str) -> String,
    pub public_rapporteur_conclusions: &'static str,
    pub ai_summary: &'static str,
    pub ai_summary_title: &'static str,
    pub analysis: &'static str,
    pub analysis_title: &'static str,
    pub legal_summary: &'static str,
    pub legal_summary_title: &'static str,
    pub headnote: &'static str,
    pub headnote_title: &'static str,
    pub read_whole_summary: &'static str,
    pub fold_summary: &'static str,
    pub conclusions_ai_summary_title: &'static str,
    /// The link to conclusions at their source, from the source's name.
    pub read_conclusions_at: fn(&str) -> String,
    pub conclusions: &'static str,
    /// The link from conclusions to the ruling they were presented in.
    pub conclusions_ruling: &'static str,
    pub print: &'static str,
    pub pdf: &'static str,
    pub reference: &'static str,
    pub copied: &'static str,
    pub copy_full_reference: &'static str,
    pub copy_short_reference: &'static str,
    pub summary: &'static str,
    pub jurisdiction: &'static str,
    pub case_name: &'static str,
    pub dockets: &'static str,
    pub solution: &'static str,
    pub domain: &'static str,
    pub chamber: &'static str,
    pub formation: &'static str,
    pub hearing_date: &'static str,
    pub decision_date: &'static str,
    /// The date of a decision read in public, as the administrative courts date theirs.
    pub reading_date: &'static str,
    pub publication: &'static str,
    pub nomenclature: &'static str,
    /// A publication code, `b`, `A`, as a reader names it; `None` for a code the table lacks.
    pub publication_label: fn(&str) -> Option<&'static str>,
    pub contents: &'static str,
    pub contents_label: &'static str,
    /// The hits a section of the text holds, from their count.
    pub hits_in_section: fn(usize) -> String,
    pub chronology: &'static str,
    pub on_appeal_from: &'static str,
    pub on_cassation_appeal_against: &'static str,
    pub on_remand_after_cassation_by: &'static str,
    pub on_application_against: &'static str,
    pub full_text: &'static str,
    pub full_text_missing: &'static str,
    /// A step of the chronology whose decision the corpus lacks.
    pub decision_unavailable: &'static str,
    pub similar: &'static str,
    pub similar_principle: &'static str,
    pub similar_case: &'static str,
    pub similar_abstained: &'static str,
    pub similar_none: &'static str,
    pub cited_by: &'static str,
    /// The decisions citing this one beyond those listed, from their count.
    pub cited_by_more: fn(i64) -> String,
    pub commentaries: &'static str,
    pub parties: &'static str,
    pub applicants: &'static str,
    pub defendants: &'static str,
    pub counsels: &'static str,
    pub counsel_one: &'static str,
    pub counsel_many: &'static str,
    pub legal_references: &'static str,
    pub search_selection: &'static str,
    pub copy: &'static str,
    pub copy_with_reference: &'static str,
    pub not_found_title: &'static str,
    pub courts: &'static str,
}
