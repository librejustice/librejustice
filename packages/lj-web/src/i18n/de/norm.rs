fn action_verb(action: &str) -> Option<&'static str> {
    match action {
        "modifie" => Some("geänderte"),
        "cree" => Some("eingefügte"),
        "abroge" => Some("aufgehobene"),
        _ => None,
    }
}

fn amends(title: &str, verbs: &str, codes: &str) -> String {
    format!("{title}: {verbs} Bestimmungen ({codes}).")
}

fn article_status(status: &str) -> Option<&'static str> {
    Some(match status {
        "VIGUEUR" => "In Kraft",
        "MODIFIE" => "Geändert",
        "ABROGE" => "Aufgehoben",
        "PERIME" => "Hinfällig",
        "REMPLACE" => "Ersetzt",
        "TRANSFERE" => "Übertragen",
        "DEPLACE" => "Verschoben",
        "ANNULE" => "Für nichtig erklärt",
        "DENONCE" => "Gekündigt",
        "DISJOINT" => "Abgetrennt",
        "VIGUEUR_DIFF" => "Inkrafttreten aufgeschoben",
        "ABROGE_DIFF" => "Aufhebung aufgeschoben",
        "MODIFIE_MORT_NE" => "Geändert, nie in Kraft getreten",
        _ => return None,
    })
}
