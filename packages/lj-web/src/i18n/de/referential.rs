const SEAT: SeatWords = SeatWords {
    container: |container| match container {
        SeatContainer::Pole(n) => format!("Abteilung {n}"),
        SeatContainer::Section(n) => format!("{n}. Sektion"),
        SeatContainer::Tribunal => "Gericht".to_string(),
        SeatContainer::TribunalFonctionPublique => {
            "Gericht für den öffentlichen Dienst".to_string()
        }
    },
    chamber: |chamber, matters| match (chamber, matters) {
        (SeatChamber::Number(n), None) => format!("{n}. Kammer"),
        (SeatChamber::Number(n), Some(matters)) => format!("{n}. Kammer für {matters}"),
        (SeatChamber::Letter(l), None) => format!("Kammer {l}"),
        (SeatChamber::Letter(l), Some(matters)) => format!("Kammer {l} für {matters}"),
        (SeatChamber::Composed(a, b), _) => format!("Kammer {a}-{b}"),
    },
    room: |matters| format!("Kammer für {matters}"),
    matter,
    and: " und ",
    section: |n| format!("{n}. Sektion"),
    letter: |l| format!("Sektion {l}"),
    joined: |joined| match joined {
        SeatJoined::SubSections(nums) if nums.len() == 1 => {
            format!("{}. Unterabteilung", seat::numbers(nums))
        }
        SeatJoined::SubSections(nums) => {
            format!("Vereinigte Unterabteilungen {}", seat::numbers(nums))
        }
        SeatJoined::Chambers(nums) => format!("Vereinigte Kammern {}", seat::numbers(nums)),
    },
    formation,
    office,
    mid: str::to_string,
};

